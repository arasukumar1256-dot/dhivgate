-- Run this in Supabase SQL Editor. Create student/host users in Supabase Auth first.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_id text unique not null,
  display_name text,
  role text not null default 'student' check (role in ('student','host')),
  created_at timestamptz not null default now()
);
create table if not exists public.questions (
  question_id text primary key,
  subject text not null,
  topic text not null,
  difficulty text,
  type text not null check (type in ('MCQ','MSQ','NAT')),
  question jsonb not null default '{}'::jsonb,
  question_text text,
  options jsonb not null default '[]'::jsonb,
  answer jsonb not null default '[]'::jsonb,
  solution jsonb not null default '{}'::jsonb,
  marks numeric not null default 1,
  negative_marks numeric not null default 0,
  source text,
  year integer,
  tags jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.exam_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  exam_name text,
  answers jsonb not null default '{}'::jsonb,
  score numeric,
  total_marks numeric,
  started_at timestamptz,
  submitted_at timestamptz default now()
);
alter table public.profiles enable row level security;
alter table public.questions enable row level security;
alter table public.exam_attempts enable row level security;
create policy "profiles read own or host" on public.profiles for select to authenticated using (id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='host'));
create policy "questions read authenticated" on public.questions for select to authenticated using (true);
create policy "host insert questions" on public.questions for insert to authenticated with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='host'));
create policy "host update questions" on public.questions for update to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='host')) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='host'));
create policy "host delete questions" on public.questions for delete to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='host'));
create policy "students insert own attempts" on public.exam_attempts for insert to authenticated with check (user_id=auth.uid());
create policy "read own attempts or host" on public.exam_attempts for select to authenticated using (user_id=auth.uid() or exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='host'));
-- IMPORTANT: create a profile row for each Auth user. Assign role='host' only to your trusted host account.
